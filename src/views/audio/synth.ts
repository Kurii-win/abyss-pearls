/**
 * Tiny WebAudio synth primitives: enveloped oscillators and filtered noise. Every sound
 * in the game is built from these at play time. No sample files, no external audio:
 * the sounds are original by construction.
 */

export interface Voice {
  readonly ctx: BaseAudioContext
  /** Where voices connect (the master gain). */
  readonly out: AudioNode
}

export interface ToneSpec {
  readonly freq: number
  /** Glide to this frequency over the note (exponential). */
  readonly freqEnd?: number
  readonly type?: OscillatorType
  /** Seconds after "now". */
  readonly at?: number
  /** Seconds. */
  readonly dur: number
  /** Peak gain before the master gain (0..1). */
  readonly gain?: number
  readonly attack?: number
}

const MIN_GAIN = 0.0001

/** Attack to `peak`, then an exponential decay to silence by `end`. */
function envelope(param: AudioParam, start: number, attack: number, end: number, peak: number): void {
  param.setValueAtTime(MIN_GAIN, start)
  param.exponentialRampToValueAtTime(Math.max(peak, MIN_GAIN), start + attack)
  param.exponentialRampToValueAtTime(MIN_GAIN, end)
}

export function tone(v: Voice, spec: ToneSpec): void {
  const { ctx, out } = v
  const start = ctx.currentTime + (spec.at ?? 0)
  const end = start + spec.dur
  const osc = ctx.createOscillator()
  const amp = ctx.createGain()
  osc.type = spec.type ?? 'sine'
  osc.frequency.setValueAtTime(spec.freq, start)
  if (spec.freqEnd) osc.frequency.exponentialRampToValueAtTime(spec.freqEnd, end)
  envelope(amp.gain, start, Math.min(spec.attack ?? 0.005, spec.dur / 2), end, spec.gain ?? 0.3)
  osc.connect(amp).connect(out)
  osc.start(start)
  osc.stop(end + 0.02)
}

export interface NoiseSpec {
  readonly at?: number
  readonly dur: number
  readonly gain?: number
  readonly filter: BiquadFilterType
  readonly freq: number
  readonly freqEnd?: number
  readonly q?: number
  readonly attack?: number
}

const noiseBuffers = new WeakMap<BaseAudioContext, AudioBuffer>()

/**
 * One second of fixed pseudo-noise per context. This is a waveform, not game
 * randomness: it is generated by a constant-seeded xorshift so the project rule
 * "nothing calls Math.random(); gameplay randomness goes through src/models/rng.ts"
 * holds, and the sound is identical on every run.
 */
function noiseBuffer(ctx: BaseAudioContext): AudioBuffer {
  let buffer = noiseBuffers.get(ctx)
  if (buffer) return buffer
  buffer = ctx.createBuffer(1, ctx.sampleRate, ctx.sampleRate)
  const data = buffer.getChannelData(0)
  let x = 0x9e3779b9
  for (let i = 0; i < data.length; i++) {
    x ^= x << 13
    x ^= x >>> 17
    x ^= x << 5
    data[i] = ((x >>> 0) / 0xffff_ffff) * 2 - 1
  }
  noiseBuffers.set(ctx, buffer)
  return buffer
}

export function noise(v: Voice, spec: NoiseSpec): void {
  const { ctx, out } = v
  const start = ctx.currentTime + (spec.at ?? 0)
  const end = start + spec.dur
  const src = ctx.createBufferSource()
  src.buffer = noiseBuffer(ctx)
  src.loop = true
  const filter = ctx.createBiquadFilter()
  filter.type = spec.filter
  filter.Q.value = spec.q ?? 1
  filter.frequency.setValueAtTime(spec.freq, start)
  if (spec.freqEnd) filter.frequency.exponentialRampToValueAtTime(spec.freqEnd, end)
  const amp = ctx.createGain()
  envelope(amp.gain, start, Math.min(spec.attack ?? 0.005, spec.dur / 2), end, spec.gain ?? 0.2)
  src.connect(filter).connect(amp).connect(out)
  src.start(start)
  src.stop(end + 0.02)
}

/** MIDI note number → Hz (A4 = 69 = 440 Hz). */
export function hz(midi: number): number {
  return 440 * 2 ** ((midi - 69) / 12)
}
